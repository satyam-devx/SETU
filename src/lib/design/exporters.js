/**
 * Export / import for design configs. Pure and DOM-free.
 *  - toCssVariables: drop-in :root/.dark CSS for external tools and docs
 *  - toDtcg:         W3C Design Tokens (DTCG draft) JSON for Figma/Style Dictionary
 *  - toSetuJson / parseImport: lossless backup & restore with strict validation
 */
import { compileDesign, varsToDeclarations } from './css.js';
import {
  COLOR_GROUPS, COLOR_LABELS, DEFAULT_DESIGN, FONT_STACKS, OPTIONS, optionCss, sanitizeConfig, validateConfig,
} from './schema.js';

export const EXPORT_FORMAT = 'setu-design-system';
export const EXPORT_SCHEMA_VERSION = 1;
export const MAX_IMPORT_BYTES = 64 * 1024;

export function toCssVariables(config) {
  const { common, light, dark } = compileDesign(config);
  return `/* SETU design tokens - generated by Design System Studio */\n:root {\n${varsToDeclarations({ ...common, ...light })}\n}\n\n.dark {\n${varsToDeclarations(dark)}\n}\n`;
}

const fontList = (value) =>
  (optionCss(OPTIONS.fontFamily, value, 'system') || FONT_STACKS.system)
    .split(',')
    .map((f) => f.trim().replace(/^"|"$/g, ''));

export function toDtcg(config) {
  const colorGroup = (palette) => {
    const out = {};
    for (const group of COLOR_GROUPS) {
      out[group.id] = {};
      for (const key of group.keys) out[group.id][key] = { $value: palette?.[key], $description: COLOR_LABELS[key] };
    }
    return out;
  };
  const t = config?.typography || {};
  const l = config?.layout || {};
  const m = config?.motion || {};
  const i = config?.icons || {};
  return {
    $description: 'SETU design tokens (W3C Design Tokens draft format)',
    color: { $type: 'color', light: colorGroup(config?.colors), dark: colorGroup(config?.darkColors) },
    font: {
      family: {
        $type: 'fontFamily',
        body: { $value: fontList(t.bodyFont) },
        heading: { $value: fontList(t.headingFont) },
        mono: { $value: fontList(t.monoFont) },
      },
      size: { base: { $type: 'dimension', $value: `${t.baseFontSize}px` } },
      weight: { body: { $type: 'fontWeight', $value: Number(t.bodyWeight) }, heading: { $type: 'fontWeight', $value: Number(t.headingWeight) } },
    },
    dimension: {
      $type: 'dimension',
      radius: { $value: optionCss(OPTIONS.radius, l.radius, '12px') },
      buttonHeight: { $value: optionCss(OPTIONS.buttonHeight, l.buttonHeight, 'standard') },
      inputHeight: { $value: optionCss(OPTIONS.inputHeight, l.inputHeight, 'standard') },
      iconSize: { $value: `${i.size}px` },
    },
    duration: { base: { $type: 'duration', $value: optionCss(OPTIONS.motionDuration, m.duration, 'normal') } },
    shadow: { card: { $type: 'shadow', $value: optionCss(OPTIONS.shadow, l.shadow, 'soft') } },
  };
}

export function toSetuJson(config, { scope = 'global' } = {}) {
  return JSON.stringify({ format: EXPORT_FORMAT, schemaVersion: EXPORT_SCHEMA_VERSION, scope, config }, null, 2);
}

/**
 * Parse a backup produced by toSetuJson (or a bare config object).
 * Strict: any invalid token rejects the import, so nothing is half-applied.
 * @returns {{ ok: boolean, config?: object, errors: string[], warnings: string[] }}
 */
export function parseImport(text) {
  const errors = [];
  const warnings = [];
  if (typeof text !== 'string' || !text.trim()) return { ok: false, errors: ['Nothing to import.'], warnings };
  if (new TextEncoder().encode(text).length > MAX_IMPORT_BYTES) {
    return { ok: false, errors: [`File is larger than ${MAX_IMPORT_BYTES / 1024} KB.`], warnings };
  }
  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch {
    return { ok: false, errors: ['This is not valid JSON.'], warnings };
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    return { ok: false, errors: ['Expected a JSON object.'], warnings };
  }
  let raw = parsed;
  if (parsed.format !== undefined) {
    if (parsed.format !== EXPORT_FORMAT) return { ok: false, errors: [`Unknown format "${parsed.format}".`], warnings };
    if (typeof parsed.schemaVersion === 'number' && parsed.schemaVersion > EXPORT_SCHEMA_VERSION) {
      warnings.push(`File uses schema v${parsed.schemaVersion}; this Studio understands v${EXPORT_SCHEMA_VERSION}. Unknown parts are ignored.`);
    }
    raw = parsed.config;
  }
  const result = validateConfig(raw);
  if (!result.valid) {
    return { ok: false, errors: result.errors.slice(0, 8).map((e) => `${e.path || 'config'}: ${e.message}`), warnings };
  }
  const known = new Set(Object.keys(DEFAULT_DESIGN));
  for (const key of Object.keys(raw)) if (!known.has(key)) warnings.push(`Ignored unknown section "${key}".`);
  return { ok: true, config: sanitizeConfig(raw), errors, warnings };
}
