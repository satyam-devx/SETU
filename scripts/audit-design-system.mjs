#!/usr/bin/env node
/** Static inventory of visual values in SETU source. Read-only; does not modify files. */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(process.argv[2] || 'src');
const out = path.resolve(process.argv[3] || 'DESIGN_SYSTEM_INVENTORY.md');
const extensions = new Set(['.js', '.jsx', '.ts', '.tsx', '.css', '.html']);
const findings = { hexColors: [], rgbHsl: [], paletteUtilities: [], fontUtilities: [], fontFamilies: [], lucideImports: [], radiusShadowUtilities: [] };
const files = [];
function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['node_modules', 'dist', 'build', '.git'].includes(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (extensions.has(path.extname(entry.name))) files.push(full);
  }
}
function scanLine(bucket, file, lineNo, line, regex) {
  const matches = [...line.matchAll(regex)].map((m) => m[0]);
  if (matches.length) findings[bucket].push({ file: path.relative(process.cwd(), file), line: lineNo, values: [...new Set(matches)], excerpt: line.trim().slice(0, 220) });
}
walk(root);
for (const file of files) {
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  lines.forEach((line, i) => {
    const n = i + 1;
    scanLine('hexColors', file, n, line, /#[0-9a-fA-F]{3,8}\b/g);
    scanLine('rgbHsl', file, n, line, /(?:rgba?|hsla?)\(\s*[^)]{1,100}\)/g);
    scanLine('paletteUtilities', file, n, line, /(?:bg|text|border|ring|fill|stroke|from|to|via)-(?:red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose|slate|gray|zinc|neutral|stone)-(?:\d{2,3}|\[#[0-9a-fA-F]{3,8}\])/g);
    scanLine('fontUtilities', file, n, line, /\b(?:font-sans|font-serif|font-mono|font-heading|text-(?:xs|sm|base|lg|xl|[2-9]xl)|tracking-[\w-]+)\b/g);
    scanLine('fontFamilies', file, n, line, /font-family\s*:\s*[^;}]+|fontFamily\s*:\s*[^,;}]+/g);
    scanLine('lucideImports', file, n, line, /from\s+['"]lucide-react['"]/g);
    scanLine('radiusShadowUtilities', file, n, line, /\b(?:rounded(?:-[a-z0-9\[\]./%-]+)?|shadow(?:-[a-z0-9\[\]./%-]+)?)\b/g);
  });
}
const total = (key) => findings[key].length;
const sections = [
  ['Hex colors', 'hexColors'], ['RGB/HSL colors', 'rgbHsl'], ['Tailwind palette utilities', 'paletteUtilities'],
  ['Typography utilities', 'fontUtilities'], ['Font-family declarations', 'fontFamilies'], ['Lucide import locations', 'lucideImports'],
  ['Radius/shadow utilities', 'radiusShadowUtilities'],
];
let md = `# SETU Design System Inventory\n\nGenerated by \`scripts/audit-design-system.mjs\`. This is a static source inventory, not a visual/browser test.\n\n`;
md += `## Summary\n\n- Source files scanned: **${files.length}**\n`;
for (const [label, key] of sections) md += `- ${label}: **${total(key)} source lines**\n`;
md += `\n## Findings\n\n`;
for (const [label, key] of sections) {
  md += `### ${label} (${total(key)} lines)\n\n`;
  if (!findings[key].length) { md += '_No matches._\n\n'; continue; }
  md += '| File | Line | Values | Source excerpt |\n|---|---:|---|---|\n';
  for (const f of findings[key]) {
    const esc = (v) => String(v).replaceAll('|', '\\|').replaceAll('`', '\\`');
    md += `| \`${esc(f.file)}\` | ${f.line} | ${esc(f.values.join(', '))} | \`${esc(f.excerpt)}\` |\n`;
  }
  md += '\n';
}
md += `## Interpretation\n\nThis report intentionally lists candidates rather than blindly rewriting them. Many radius, font-size, and icon utilities are legitimate semantic variants and should not be globally replaced without checking component intent. Hard-coded brand/status colors should be migrated to semantic tokens; icon size/stroke can be centralized by using \`DesignIcon\` from \`src/components/shared/DesignIcon.jsx\`.\n`;
fs.writeFileSync(out, md);
console.log(`Scanned ${files.length} source files. Wrote ${out}`);
for (const [label, key] of sections) console.log(`${label}: ${total(key)} lines`);
