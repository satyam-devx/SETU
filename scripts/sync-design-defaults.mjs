#!/usr/bin/env node
/**
 * Generates the baseline CSS tokens in src/index.css from DEFAULT_DESIGN, so the
 * stylesheet and the runtime provider can never disagree (a disagreement shows up
 * as a visible colour jump right after React mounts).
 *
 *   node scripts/sync-design-defaults.mjs          # rewrite the generated block
 *   node scripts/sync-design-defaults.mjs --check  # exit 1 if the file is stale
 *
 * The generated block is intentionally unlayered, so it wins over @layer rules,
 * and `.dark` is emitted after `:root` so dark mode overrides light.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileDesign, varsToDeclarations } from '../src/lib/design/css.js';
import { DEFAULT_DESIGN } from '../src/lib/design/schema.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cssPath = path.join(root, 'src/index.css');
const BEGIN = '/* >>> design-defaults:begin (generated by scripts/sync-design-defaults.mjs; do not edit) >>> */';
const END = '/* <<< design-defaults:end <<< */';

export function buildBlock() {
  const { common, light, dark } = compileDesign(DEFAULT_DESIGN);
  return [
    BEGIN,
    ':root {',
    varsToDeclarations({ ...common, ...light }),
    '}',
    '.dark {',
    varsToDeclarations(dark),
    '}',
    END,
  ].join('\n');
}

/** One-time migration from the hand-written token blocks to the generated block. */
function migrate(css) {
  const layerStart = css.indexOf('@layer base {\n  :root {');
  if (layerStart !== -1) {
    const darkAt = css.indexOf('.dark {', layerStart);
    const layerEnd = css.indexOf('\n}\n', darkAt) + 3;
    css = `${css.slice(0, layerStart)}/* Colour/typography/layout tokens live in the generated design-defaults block below. */\n${css.slice(layerEnd)}`;
  }
  const studioStart = css.indexOf('/* Design System Studio runtime tokens.');
  if (studioStart === -1) throw new Error('Could not find the Design System Studio token block to replace.');
  const lastToken = css.indexOf('--chart-5:', studioStart);
  const studioEnd = css.indexOf('}\n', lastToken) + 2;
  return `${css.slice(0, studioStart)}${buildBlock()}\n${css.slice(studioEnd)}`;
}

export function sync(css) {
  const a = css.indexOf(BEGIN);
  const b = css.indexOf(END);
  if (a === -1 || b === -1) return migrate(css);
  return `${css.slice(0, a)}${buildBlock()}${css.slice(b + END.length)}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const current = fs.readFileSync(cssPath, 'utf8');
  const next = sync(current);
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error('src/index.css design tokens are stale. Run: node scripts/sync-design-defaults.mjs');
      process.exit(1);
    }
    console.log('src/index.css design tokens are in sync with DEFAULT_DESIGN.');
  } else if (next !== current) {
    fs.writeFileSync(cssPath, next);
    console.log('Updated src/index.css design-defaults block.');
  } else {
    console.log('src/index.css already up to date.');
  }
}
